import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { stringify as stringifyYaml } from "yaml";
import { loadConfig, type ResolvedConfig } from "../config/config.js";
import {
  agentPermissions,
  buildAgentDefinitions,
  expandAgentVariants,
  isVariantAgentName,
  loadBuiltinAgentDefinitions,
  loadProjectAgentDefinitions,
} from "../opencode/agents.js";
import { toPermissionRuleset } from "../security/policy.js";
import type { AgentDefinition } from "../types/index.js";

/**
 * Writes the bridge agents as OpenCode 2.x agent files, so a server the bridge did not
 * spawn (the OpenCode Desktop service, `opencode.url`) knows them natively.
 *
 * Why: on an external server the bridge cannot inject its agents. It then falls back to the
 * server's default agent with the role prompt prepended, and enforcement rests on the
 * per-session ruleset alone. Installed files add a second, server-side layer (system prompt +
 * `permissions` frontmatter) generated from the same policy, so the two can never drift.
 * Permission variants (`<name>__rw`, ...) are installed hidden, so `allow_edits` /
 * `allow_bash` overrides bind to a matching server agent instead of a stricter base one.
 */

export const GENERATED_MARKER = "# generated by claude-opencode-mcp install-agents";

export interface InstallAgentsOptions {
  /** Project directory: installs into <dir>/.opencode/agents. */
  dir?: string;
  /** Install into the user's global OpenCode config (~/.config/opencode/agents). */
  global?: boolean;
  /** Overwrite files that were not generated by this command. */
  force?: boolean;
  /** Print what would be written without touching disk. */
  dryRun?: boolean;
  env?: NodeJS.ProcessEnv;
}

export function globalOpenCodeAgentsDir(env: NodeJS.ProcessEnv = process.env): string {
  const base = env.XDG_CONFIG_HOME?.trim() || path.join(os.homedir(), ".config");
  return path.join(base, "opencode", "agents");
}

export function renderAgentFile(definition: AgentDefinition, config: ResolvedConfig): string {
  const frontmatter: Record<string, unknown> = {
    description: definition.description,
    mode: definition.mode,
    ...(isVariantAgentName(definition.name) ? { hidden: true } : {}),
    permissions: toPermissionRuleset(agentPermissions(definition, config)),
  };
  const yaml = stringifyYaml(frontmatter, { lineWidth: 0 }).trimEnd();
  return `---\n${GENERATED_MARKER} — regenerate instead of editing\n${yaml}\n---\n\n${definition.prompt.trim()}\n`;
}

function isGenerated(file: string): boolean {
  try {
    return fs.readFileSync(file, "utf8").includes(GENERATED_MARKER);
  } catch {
    return false;
  }
}

export async function runInstallAgents(options: InstallAgentsOptions): Promise<number> {
  const env = options.env ?? process.env;
  if (!options.global && !options.dir) {
    process.stderr.write("install-agents: pass --dir <project> or --global\n");
    return 2;
  }
  const projectDir = options.dir ? path.resolve(options.dir) : null;
  const target = projectDir
    ? path.join(projectDir, ".opencode", "agents")
    : globalOpenCodeAgentsDir(env);

  const { config } = await loadConfig({ env, ...(projectDir ? { cwd: projectDir } : {}) });
  const [builtin, project] = await Promise.all([
    loadBuiltinAgentDefinitions(),
    projectDir ? loadProjectAgentDefinitions(projectDir) : Promise.resolve([]),
  ]);
  const definitions = expandAgentVariants(buildAgentDefinitions({ builtin, project, config }));

  if (!options.dryRun) await fs.promises.mkdir(target, { recursive: true });
  let written = 0;
  let skipped = 0;
  for (const definition of definitions) {
    const file = path.join(target, `${definition.name}.md`);
    if (fs.existsSync(file) && !isGenerated(file) && !options.force) {
      process.stdout.write(`! skipped ${file} (not generated by this command; use --force)\n`);
      skipped += 1;
      continue;
    }
    const contents = renderAgentFile(definition, config);
    if (options.dryRun) {
      process.stdout.write(`--- ${file}\n${contents}\n`);
    } else {
      await fs.promises.writeFile(file, contents, "utf8");
      process.stdout.write(`✓ ${file}\n`);
    }
    written += 1;
  }
  process.stdout.write(
    `\n${options.dryRun ? "Would write" : "Wrote"} ${written} agent file(s) to ${target}` +
      (skipped ? `, skipped ${skipped}` : "") +
      ".\nThe OpenCode Desktop service picks them up without a restart.\n",
  );
  return skipped > 0 ? 1 : 0;
}
